export function buildQuoteTerms(rawLocale?: unknown, validityDays = 7, wireCost = 20): string {
  const loc = normalizePdfLocale(rawLocale);
  const fn = QUOTE_TERMS_BUILDERS[loc] || QUOTE_TERMS_BUILDERS.en;
  return fn(validityDays, wireCost);
}

/**
 * Formats an AGENTS.md-compliant package title derived purely from authentic hardware attributes.
 * Never outputs obsolete 3-tier terms ("Budget", "Recommended", "Premium", "Plan 1/2/3").
 */
export function formatHardwarePackageTitle(quote: Record<string, any> | null | undefined): string {
  if (!quote) return "Custom CCTV Package";
  const req = quote.requirementSnapshot || quote.requirement || quote || {};
  const cameras = Number(req.camera_count || quote.camera_count || quote.total_cameras || 0);
  const rawBrand = String(
    req.preferred_brand || req.brand || quote.brand || quote.preferred_brand || ""
  ).trim();
  const brand =
    rawBrand && !["budget", "recommended", "premium", "essential", "pro", "elite"].includes(rawBrand.toLowerCase())
      ? rawBrand
      : "";

  const planTypeRaw = String(quote.plan_type || req.plan_type || "").trim();
  const isLegacyTier = /^(budget|recommended|premium|value|pro|elite|essential|plan\s*[123])$/i.test(
    planTypeRaw
  );
  // If plan_type already holds Brand_Tech_Resolution (e.g. "CPPLUS_IP_5MP"), extract clean attributes
  const parts = !isLegacyTier && planTypeRaw.includes("_") ? planTypeRaw.split("_") : [];
  const techRaw = String(req.technology_preference || req.technology || quote.technology || parts[1] || "").trim();
  const resRaw = String(req.resolution || quote.resolution || parts[2] || "").trim();
  const recordingDays = Number(req.recording_days || quote.recording_days || 0);
  const storageStr = String(quote.storage_label || quote.storage || "").trim();

  const camPrefix = cameras > 0 ? `${cameras}-Camera` : "";
  const techLabel = techRaw || "HD";
  const labelCore = [camPrefix, brand, resRaw, techLabel, "CCTV Package"]
    .filter(Boolean)
    .join(" ");
  const suffix = storageStr
    ? ` (${storageStr})`
    : recordingDays > 0
      ? ` (${recordingDays}-Day Recording)`
      : "";
  return `${labelCore}${suffix}`;
}
