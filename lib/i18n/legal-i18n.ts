export function interpolateLegalText(
  text: string,
  meta: { lastUpdated: string; companyName: string; domain: string; phone: string; email: string; address: string }
): string {
  return text
    .replace(/\{lastUpdated\}/g, meta.lastUpdated)
    .replace(/\{companyName\}/g, meta.companyName)
    .replace(/\{domain\}/g, meta.domain)
    .replace(/\{phone\}/g, meta.phone)
    .replace(/\{email\}/g, meta.email)
    .replace(/\{address\}/g, meta.address);
}
