// ── 1. WIPE ALL PRODUCTS ──────────────────────────────────────────────────
async function wipeAllProducts() {
  console.log("==> Step 1: Wiping all existing products from Firestore collection 'products'...");
  const snap = await db.collection('products').get();
  console.log(`Found ${snap.docs.length} products to delete.`);
  
  const batchSize = 400;
  let batch = db.batch();
  let count = 0;

  for (const doc of snap.docs) {
    batch.delete(doc.ref);
    count++;
    if (count % batchSize === 0) {
      await batch.commit();
      batch = db.batch();
      console.log(`Deleted ${count} products...`);
    }
  }

  if (count % batchSize !== 0) {
    await batch.commit();
  }

  // Verify deletion
  const verifySnap = await db.collection('products').get();
  console.log(`Verification: Current products in Firestore = ${verifySnap.docs.length}`);
  if (verifySnap.docs.length !== 0) {
    throw new Error("Failed to completely wipe products collection!");
  }
  console.log("==> Successfully wiped products down to 0!");
}

