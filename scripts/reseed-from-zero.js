function getMarginForProduct(p) {
  const cat = p.category;
  const brand = (p.brand || '').toLowerCase();
  const path = (p.catalog_path || '').toLowerCase();
  const name = (p.display_name || '').toLowerCase();
  if (cat === 'storage') {
    if (path.includes('microsd') || name.includes('sd card')) return 15;
    return 8;
  }
  if (cat === 'cctv_camera') {
    if (brand.includes('a+') || brand.includes('generic')) return 20;
    return 15;
  }
  if (cat === 'recorder') return 15;
  if (cat === 'power_device') {
    if (path.includes('poe') || name.includes('poe')) return 15;
    return 20;
  }
  if (cat === 'cable') return 20;
  if (cat === 'rack') return 25;
  if (cat === 'network') return 15;
  if (cat === 'hdmi_cable') return 25;
  if (cat === 'display') return 15;
  if (cat === 'connector') return 30;
  if (cat === 'camera_mount') return 25;
  return 15;
}

async function reseedFromZero() {
  await wipeAllProducts();

  console.log("\n==> Step 2: Ingesting verified non-project retail catalog directly from user screenshots and downloads...");
  const batch = db.batch();
  let count = 0;

  for (const [id, data] of Object.entries(CLEAN_CATALOG)) {
    // Strict assertions
    if (!data.unit_price || data.unit_price <= 0) {
      throw new Error(`CRITICAL: Product ${id} has zero price! Aborting.`);
    }
    const checkStr = `${data.brand} ${data.display_name} ${data.technical_name}`.toLowerCase();
    if (checkStr.includes("project") || checkStr.includes("nc34tp3")) {
      throw new Error(`CRITICAL: Project model ${id} leaked into catalog! Aborting.`);
    }

    const margin = getMarginForProduct(data);
    const baseCost = Math.round(data.unit_price / (1 + margin / 100));

    const docRef = db.collection('products').doc(id);
    batch.set(docRef, {
      ...data,
      base_cost: baseCost,
      margin_percentage: margin,
      id,
      created_at: ts,
      updated_at: ts
    });
    count++;
  }

  await batch.commit();
  console.log(`==> Successfully committed ${count} clean, verified retail products into Firestore!`);

  // Final validation
  const finalSnap = await db.collection('products').get();
  console.log(`\nFinal Database Count: ${finalSnap.docs.length} active products.`);

  const catSummary = {};
  finalSnap.docs.forEach(d => {
    const p = d.data();
    catSummary[p.category] = (catSummary[p.category] || 0) + 1;
  });
  console.log("Category breakdown:", catSummary);

  process.exit(0);
}

reseedFromZero().catch(err => {
  console.error("FATAL ERROR during reseed:", err);
  process.exit(1);
});
