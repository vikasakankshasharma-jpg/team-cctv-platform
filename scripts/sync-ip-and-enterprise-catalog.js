async function syncIPAndEnterpriseCatalog() {
  console.log('Seeding curated IP & Enterprise catalog into Firestore...');
  const batch = db.batch();
  let count = 0;

  for (const [id, data] of Object.entries(IP_AND_ENTERPRISE_PRODUCTS)) {
    const docRef = db.collection('products').doc(id);
    batch.set(docRef, {
      ...data,
      id,
      created_at: ts,
      updated_at: ts
    }, { merge: true });
    count++;
  }

  await batch.commit();
  console.log(`Successfully synced ${count} IP & Enterprise products to Firestore!`);
  process.exit(0);
}

syncIPAndEnterpriseCatalog().catch(err => {
  console.error('Error syncing IP products:', err);
  process.exit(1);
});
