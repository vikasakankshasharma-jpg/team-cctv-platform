async function seed() {
  console.log(`Starting to seed ${wirelessProducts.length} cameras into Firestore...`);
  const batch = db.batch();
  const now = admin.firestore.FieldValue.serverTimestamp();

  for (const item of wirelessProducts) {
    const docRef = db.collection('products').doc(item.id);
    const docSnap = await docRef.get();
    const existing = docSnap.exists ? docSnap.data() : {};

    const payload = {
      ...item,
      created_at: existing.created_at || now,
      updated_at: now
    };

    batch.set(docRef, payload, { merge: true });
    console.log(`Prepared [${item.id}] - ${item.display_name} (Cost: ₹${item.base_cost}, Sell: ₹${item.unit_price})`);
  }

  await batch.commit();
  console.log('✅ Successfully seeded all 22 cameras into Firestore products collection!');
}

seed().then(() => process.exit(0)).catch(err => {
  console.error('❌ Error seeding cameras:', err);
  process.exit(1);
});
