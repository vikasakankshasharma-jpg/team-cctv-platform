async function seedCpPlusProducts() {
  const { db, ts } = getDb();
  console.log("Adding 6 CP Plus Wi-Fi & 4G PTZ Cameras to Firestore `products` collection...");

  let added = 0;
  for (const [id, prodData] of Object.entries(NEW_CP_PLUS_PRODUCTS)) {
    const docRef = db.collection("products").doc(id);
    const existing = await docRef.get();

    await docRef.set(
      {
        ...prodData,
        created_at: existing.exists ? existing.data()?.created_at || ts : ts,
        updated_at: ts,
      },
      { merge: true }
    );

    console.log(` ✅ Seeded: [${id}] ${prodData.display_name} -> Cost: ₹${prodData.base_cost} | Retail: ₹${prodData.unit_price}`);
    added++;
  }

  console.log(`\n🎉 Successfully added all ${added} CP Plus items to the product list!`);
}

seedCpPlusProducts().catch((err) => {
  console.error("❌ Error adding CP Plus products:", err);
  process.exit(1);
});
